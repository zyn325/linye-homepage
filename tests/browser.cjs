const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const origin = process.env.TEST_ORIGIN || 'http://localhost:5173';

async function main() {
  fs.mkdirSync('/tmp/lightpath-screenshots', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1365, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.screenshot({ path: '/tmp/lightpath-screenshots/home.png', fullPage: true });
  await page.locator('#open-ai').click();
  await page.locator('#nickname').fill('测试玩家');
  await page.locator('#start-game').click();
  await page.locator('#board canvas').waitFor();
  await page.waitForTimeout(400);
  const clickCell = async (target, x, y) => {
    const canvas = await target.locator('#board canvas').boundingBox();
    await target.locator('#board canvas').click({ position: {
      x: (30 + (x - 0.5) * 40) / 580 * canvas.width,
      y: (30 + (13.5 - y) * 40) / 580 * canvas.height
    } });
  };
  await clickCell(page, 1, 1);
  await page.locator('#confirm-move').click();
  await page.waitForFunction(() => document.querySelector('#history-count').textContent === '2', null, { timeout: 20000 });
  await page.screenshot({ path: '/tmp/lightpath-screenshots/game.png', fullPage: true });
  await page.locator('#undo').click();
  assert.equal(await page.locator('#history-count').textContent(), '0');
  await clickCell(page, 5, 9);
  assert.equal(await page.locator('#confirm-move').isDisabled(), true);
  await clickCell(page, 3, 4);
  await page.locator('#backslash').click();
  await page.locator('#confirm-move').click();
  await page.waitForFunction(() => document.querySelector('#history-count').textContent === '2', null, { timeout: 20000 });
  await page.reload();
  await page.locator('.resume').click();
  assert.equal(await page.locator('#history-count').textContent(), '2');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  await page.screenshot({ path: '/tmp/lightpath-screenshots/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const red = await browser.newPage();
  const blue = await browser.newPage();
  for (const target of [red, blue]) target.on('pageerror', error => errors.push(error.message));
  await red.goto(origin);
  await red.locator('#open-friend').click();
  await red.locator('#nickname').fill('红方玩家');
  await red.locator('#start-game').click();
  await red.locator('#room-code').waitFor({ state: 'visible' });
  const code = await red.locator('#room-code').textContent();
  await blue.goto(`${origin}/?room=${code}`);
  await blue.locator('#nickname').fill('蓝方玩家');
  await blue.locator('#start-game').click();
  await blue.locator('#ready').waitFor({ state: 'visible' });
  await red.locator('#ready').click();
  await blue.waitForFunction(() => document.querySelector('#red-detail').textContent.includes('已准备'));
  await blue.locator('#ready').click();
  await red.locator('#move-controls').waitFor({ state: 'visible' });
  await red.locator('#board canvas').waitFor();
  await clickCell(red, 1, 1);
  await red.locator('#confirm-move').click();
  await blue.waitForFunction(() => document.querySelector('#history-count').textContent === '1');
  await blue.reload();
  await blue.locator('#play').waitFor({ state: 'visible' });
  assert.equal(await blue.locator('#history-count').textContent(), '1');
  await red.locator('#offer-draw').click();
  await blue.locator('#accept-draw').waitFor({ state: 'visible' });
  await blue.locator('#accept-draw').click();
  await red.locator('#restart').waitFor({ state: 'visible' });
  await red.locator('#restart').click();
  await blue.waitForFunction(() => document.querySelector('#status-title').textContent.includes('平分秋色'));
  await blue.waitForTimeout(200);
  await blue.locator('#restart').click();
  await red.waitForFunction(() => document.querySelector('#history-count').textContent === '0');
  await page.locator('#rules-open').click();
  await page.screenshot({ path: '/tmp/lightpath-screenshots/rules.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('浏览器检查通过：人机回应、悔棋、禁放格、朝向、刷新、手机布局、房间、准备、同步、恢复、和棋、再来一局。');
  await browser.close();
}
main().catch(error => { console.error(error); process.exit(1); });
